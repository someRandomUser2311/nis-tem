// Docs as a folder of GitHub-flavoured Markdown: README.md (overview, guides index, endpoint
// index), one file per guide page and one file per top-level folder. Reads well on GitHub,
// GitLab or any wiki, and diffs cleanly in git.
import { slugify } from "../linked";
import type { DocsEndpoint, DocsModel, DocsParam, DocsSection } from "./model";
import type { SchemaRow } from "./schema";

export const GENERATED_MARK = "<!-- Generated by Localpost. Edit the docs in Localpost; changes here are overwritten. -->";

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const fence = (code: string, lang = "") => {
  const ticks = code.includes("```") ? "````" : "```";
  return `${ticks}${lang}\n${code}\n${ticks}`;
};

function params(title: string, ps: DocsParam[]): string {
  if (!ps.length) return "";
  const rows = ps.map((p) => {
    const extra = [
      p.enum?.length ? `One of: ${p.enum.map((v) => `\`${v}\``).join(", ")}` : "",
      p.default ? `Default: \`${p.default}\`` : "",
      p.example || p.value ? `Example: \`${p.example || p.value}\`` : "",
      p.deprecated ? "**Deprecated.**" : "",
    ].filter(Boolean).join(" · ");
    return `| \`${cell(p.name)}\`${p.required ? " *" : ""} | ${cell(p.type ?? "string")}${p.format ? ` (${cell(p.format)})` : ""} | ${cell([p.description, extra].filter(Boolean).join(" — "))} |`;
  });
  return `${title ? `**${title}**\n\n` : ""}| Name | Type | Description |\n| --- | --- | --- |\n${rows.join("\n")}\n`;
}

function fields(rows: SchemaRow[]): string {
  if (!rows.length) return "";
  return `| Field | Type | Description |\n| --- | --- | --- |\n${rows.map((r) =>
    `| ${"&nbsp;&nbsp;".repeat(r.depth)}\`${cell(r.name)}\`${r.required ? " *" : ""} | ${cell(r.type)}${r.format ? ` (${cell(r.format)})` : ""} | ${cell([r.variant ? `(${r.variant})` : "", r.description ?? "", r.enum ? `One of: ${r.enum.map((v) => `\`${JSON.stringify(v)}\``).join(", ")}` : "", r.deprecated ? "**Deprecated.**" : ""].filter(Boolean).join(" "))} |`).join("\n")}\n`;
}

/** Link from one generated file to another (files live at the root or one folder down). */
function relative(from: string, to: string): string {
  if (from === to) return "";
  const fromDir = from.includes("/") ? from.slice(0, from.lastIndexOf("/")) : "";
  const toDir = to.includes("/") ? to.slice(0, to.lastIndexOf("/")) : "";
  if (fromDir === toDir) return to.slice(to.lastIndexOf("/") + 1);
  return fromDir ? `../${to}` : to;
}

/** GitHub's heading anchor for a heading text. */
const ghAnchor = (text: string) => text.toLowerCase().trim().replace(/[^\p{L}\p{N}\s-]/gu, "").replace(/\s/g, "-");

export function buildMarkdownDocs(m: DocsModel): { path: string; content: string }[] {
  // Where every anchor ends up: file + GitHub heading anchor, for cross-links.
  const where = new Map<string, { file: string; hash: string }>();
  const topFile = (s: DocsSection) => (s.trail.length ? s.trail[0] : s.kind === "folder" ? s.name : "");
  const fileNames = new Map<string, string>();
  const used = new Set(["README.md"]);
  const fileFor = (top: string) => {
    if (!fileNames.has(top)) {
      let f = `${top ? slugify(top) : "endpoints"}.md`;
      for (let n = 2; used.has(f); n++) f = `${top ? slugify(top) : "endpoints"}-${n}.md`;
      used.add(f);
      fileNames.set(top, f);
    }
    return fileNames.get(top)!;
  };
  const epHeading = (e: DocsEndpoint) => `${e.method} ${e.name}`;
  for (const p of m.pages) {
    let f = `guides/${slugify(p.title)}.md`;
    for (let n = 2; used.has(f); n++) f = `guides/${slugify(p.title)}-${n}.md`;
    used.add(f);
    where.set(p.anchor, { file: f, hash: "" });
  }
  for (const s of m.sections) where.set(s.anchor, { file: fileFor(topFile(s)), hash: ghAnchor(s.kind === "folder" ? s.name : epHeading(s)) });

  /** Rewrite `#req:<id>` and `#<anchor>` links relative to `from`. */
  const links = (md: string, from: string) => md.replace(/\]\(#(req:)?([\w-]+)\)/g, (all, req: string | undefined, id: string) => {
    const anchor = req ? m.anchors[id] : id;
    const w = anchor ? where.get(anchor) : undefined;
    if (!w) return all;
    return `](${relative(from, w.file)}${w.hash ? `#${w.hash}` : ""})`;
  });

  const endpointMd = (e: DocsEndpoint, file: string, level: number) => {
    const h = "#".repeat(level);
    const out = [`${h} ${epHeading(e)}${e.status && e.status !== "stable" ? ` _(${e.status})_` : ""}`, "", `\`${e.method} ${e.url}\``, ""];
    if (e.tags.length) out.push(`Tags: ${e.tags.map((t) => `\`${t}\``).join(" ")}`, "");
    if (e.description) out.push(links(e.description, file), "");
    if (e.auth) out.push(`**Authentication:** ${e.auth}`, "");
    for (const [t, ps] of [["Path variables", e.pathVariables], ["Query parameters", e.query], ["Headers", e.headers]] as const) {
      const p = params(t, ps);
      if (p) out.push(p);
    }
    if (e.body) {
      out.push(`**Request body**${e.body.mode === "formdata" ? " (multipart/form-data)" : e.body.mode === "urlencoded" ? " (x-www-form-urlencoded)" : ""}`, "");
      if (e.body.fields) out.push(params("", e.body.fields));
      if (e.body.schemaRows.length) out.push(fields(e.body.schemaRows));
      if (e.body.example) out.push(fence(e.body.example, e.body.language === "graphql" ? "graphql" : e.body.language ?? ""), "");
    }
    if (e.responseSchemaRows.length || e.examples.length) {
      out.push("**Responses**", "");
      if (e.responseSchemaRows.length) out.push(fields(e.responseSchemaRows));
      for (const ex of e.examples) {
        out.push(`<details${ex === e.examples[0] ? " open" : ""}><summary><code>${ex.status}</code> ${ex.name.replace(/</g, "&lt;")}</summary>`, "");
        if (ex.description) out.push(links(ex.description, file), "");
        if (ex.body) out.push(fence(ex.body, ex.language === "text" ? "" : ex.language), "");
        if (ex.schemaRows.length) out.push(fields(ex.schemaRows));
        out.push("</details>", "");
      }
    }
    const sample = e.samples[0];
    if (sample) out.push(`**Example request** (${sample.label})`, "", fence(sample.code, sample.lang === "curl" || sample.lang === "httpie" || sample.lang === "wget" ? "bash" : sample.lang === "fetch" || sample.lang === "axios" ? "js" : sample.lang), "");
    return out.join("\n");
  };

  const files = new Map<string, string[]>();
  const push = (file: string, text: string) => { if (!files.has(file)) files.set(file, []); files.get(file)!.push(text); };
  for (const s of m.sections) {
    const file = fileFor(topFile(s));
    // Folder at depth d → heading level d+1 (the top folder is the file's title); an endpoint
    // under d folders → level d+1. Endpoints at the collection root go under "# Endpoints".
    if (s.kind === "folder") {
      push(file, [`${"#".repeat(Math.min(6, s.depth + 1))} ${s.name}`, "", s.description ? links(s.description, file) : "", ""].join("\n"));
    } else {
      if (!s.trail.length && !files.has(file)) push(file, "# Endpoints\n");
      push(file, endpointMd(s, file, Math.min(6, Math.max(2, s.depth + 1))));
    }
  }

  const readme = [
    GENERATED_MARK, "",
    `# ${m.title}${m.version ? ` (v${m.version})` : ""}`, "",
    m.description ? links(m.description, "README.md") : "", "",
    m.auth ? `**Authentication:** ${m.auth}\n` : "",
    m.pages.length ? `## Guides\n\n${m.pages.map((p) => `- [${p.title}](${where.get(p.anchor)!.file})`).join("\n")}\n` : "",
    m.sections.length ? `## Endpoints\n\n${m.sections.map((s) => {
      const w = where.get(s.anchor)!;
      const indent = "  ".repeat(s.depth);
      return s.kind === "folder" ? `${indent}- **[${s.name}](${w.file}#${w.hash})**` : `${indent}- [\`${s.method}\` ${s.name}](${w.file}#${w.hash})`;
    }).join("\n")}\n` : "",
    "", "_Generated by Localpost._", "",
  ].filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n");

  return [
    { path: "README.md", content: readme },
    ...m.pages.map((p) => {
      const f = where.get(p.anchor)!.file;
      return { path: f, content: `${GENERATED_MARK}\n\n# ${p.title}\n\n${links(p.body, f)}\n` };
    }),
    ...[...files.entries()].map(([path, parts]) => ({ path, content: `${GENERATED_MARK}\n\n[← ${m.title}](README.md)\n\n${parts.join("\n")}\n` })),
  ];
}
